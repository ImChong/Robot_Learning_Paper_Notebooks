import json
import os
import subprocess
from pathlib import Path

from scripts.prepare_pages import build_paper_previews

REPO_ROOT = Path(__file__).resolve().parent.parent


def test_build_paper_previews_covers_categories_and_subcategories():
    sample = {
        "01_Foundational_RL": {
            "display_name": "Foundational RL",
            "zhname": "强化学习基础",
            "papers": [
                {
                    "title": "PPO",
                    "zh_title": "近端策略优化算法 (PPO)",
                    "url": "/papers/01_Foundational_RL/PPO/PPO.html",
                    "published_date_en": "Jul 20, 2017 (arXiv)",
                    "published_date_zh": "2017年7月20日（arXiv）",
                    "summary_zh": "PPO 简介",
                    "arxiv": "1707.06347",
                    "has_open_source": True,
                    "health_score": 6,
                    "health_label_en": "Note health 6/6",
                    "health_label_zh": "笔记健康度 6/6",
                    "explainer_scenes": 5,
                    "video_seconds": 230,
                }
            ],
            "subcategories": [
                {
                    "name": "Sub",
                    "zhname": "子类",
                    "papers": [
                        {
                            "title": "SubPaper",
                            "zhname": "子论文",
                            "url": "/papers/01_Foundational_RL/SubPaper/SubPaper.html",
                            "has_open_source": False,
                        }
                    ],
                }
            ],
        }
    }

    previews = build_paper_previews(sample)
    assert set(previews.keys()) == {
        "/papers/01_Foundational_RL/PPO/PPO.html",
        "/papers/01_Foundational_RL/SubPaper/SubPaper.html",
    }
    ppo = previews["/papers/01_Foundational_RL/PPO/PPO.html"]
    assert ppo["t"] == "PPO"
    assert ppo["zt"] == "近端策略优化算法 (PPO)"
    assert ppo["c"] == "Foundational RL"
    assert ppo["zc"] == "强化学习基础"
    assert ppo["os"] == 1
    assert ppo["hs"] == 6
    assert ppo["es"] == 5
    assert ppo["vs"] == 230

    sub = previews["/papers/01_Foundational_RL/SubPaper/SubPaper.html"]
    assert sub["zt"] == "子论文"
    assert "os" not in sub


def test_generated_paper_previews_json_matches_papers_json():
    papers_data = json.loads((REPO_ROOT / "_data" / "papers.json").read_text(encoding="utf-8"))
    previews_path = REPO_ROOT / "assets" / "data" / "paper-previews.json"
    assert previews_path.is_file(), "assets/data/paper-previews.json should be generated by prepare_pages.py"

    previews = json.loads(previews_path.read_text(encoding="utf-8"))
    expected = build_paper_previews(papers_data)
    assert len(previews) == len(expected)
    assert set(previews.keys()) == set(expected.keys())


def test_default_layout_wires_paper_preview_script():
    layout = (REPO_ROOT / "_layouts" / "default.html").read_text(encoding="utf-8")
    assert "/assets/js/paper-preview.js" in layout
    assert "data-previews-url=" in layout
    assert "/assets/data/paper-previews.json" in layout
    assert "data-baseurl=" in layout
    assert "data-health-max=" in layout


def test_paper_preview_js_syntax_and_guards():
    js_path = REPO_ROOT / "assets" / "js" / "paper-preview.js"
    js_text = js_path.read_text(encoding="utf-8")
    assert ".tt-node" in js_text
    assert ".paper-health[data-health-score]" in js_text
    assert ".paper-card" in js_text
    assert "cl-lang-changed" in js_text

    if os.system("which node >/dev/null 2>&1") == 0:
        res = subprocess.run(["node", "--check", str(js_path)], capture_output=True, text=True)
        assert res.returncode == 0, res.stderr
